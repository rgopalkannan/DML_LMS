import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  IsArray,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
  ValidateNested
} from 'class-validator';
import { LIMITS, type QuestionType } from '../../../common/constants/domain';

const MAX_QUESTIONS = 50;
const MAX_OPTIONS = 10;

export class AnswerDto {
  @IsUUID()
  questionId!: string;

  @IsArray()
  @ArrayMaxSize(MAX_OPTIONS)
  @IsUUID('all', { each: true })
  optionIds!: string[];

  @IsOptional()
  @IsString()
  @MaxLength(LIMITS.SHORT_ANSWER_MAX_LENGTH)
  text?: string;
}

export class SubmitAttemptRequestDto {
  @IsString()
  @MaxLength(2000)
  drawToken!: string;

  /** Generated by the client per attempt, so a repeated submit is stored once. */
  @Matches(/^[A-Za-z0-9_-]{16,64}$/)
  idempotencyKey!: string;

  @IsArray()
  @ArrayMaxSize(MAX_QUESTIONS)
  @ValidateNested({ each: true })
  @Type(() => AnswerDto)
  answers!: AnswerDto[];
}

export interface DrawnQuestionDto {
  id: string;
  type: QuestionType;
  prompt: string;
  options: { id: string; label: string }[];
}

export interface QuizDrawResponseDto {
  drawToken: string;
  passPercent: number;
  questions: DrawnQuestionDto[];
}

export interface AttemptResultResponseDto {
  attemptId: string;
  score: number;
  total: number;
  percent: number;
  passed: boolean;
  passPercent: number;
  certificateId: string | null;
  results: { questionId: string; correct: boolean; correctOptionIds: string[]; explanation: string | null }[];
}
